/**
 * Returns a localized copy of a ToolItem based on the selected LanguageCode.
 */
export function getTranslatedTool(tool: ToolItem, lang: LanguageCode): ToolItem {
  if (lang === 'en') return tool;
  const translation = TOOL_TRANSLATIONS[tool.id]?.[lang];
  if (!translation) return tool;
  return {
    ...tool,
    name: translation.name || tool.name,
    shortDesc: translation.shortDesc || tool.shortDesc,
  };
}

/**
 * Returns a translated string for a given key, falling back to English or custom fallback.
 */
export function getTranslation(lang: LanguageCode, key: string, fallback?: string): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  if (dict && dict[key]) return dict[key];
  if (TRANSLATIONS.en && TRANSLATIONS.en[key]) return TRANSLATIONS.en[key];
  return fallback || key;
}
